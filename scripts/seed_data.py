def try_seed_from_api(db):
    """尝试从掌上高考 API 补充更多数据"""
    try:
        from scrapers.zhiyuan import fetch_admission_scores, fetch_school_list
    except ImportError:
        print("  [跳过] 采集器不可用")
        return 0

    total_api = 0

    # 尝试获取更多院校
    print("  尝试从掌上高考 API 获取院校数据...")
    for province in ["湖北", "河南", "山东", "广东", "四川", "湖南", "江苏", "浙江"]:
        try:
            schools = fetch_school_list(province=province, page_size=20)
            for s in schools:
                sname = s.get("name", s.get("school_name", ""))
                if not sname or db.query(School).filter(School.name == sname).first():
                    continue
                db.add(
                    School(
                        name=sname,
                        province=s.get("province", province),
                        city=s.get("city", ""),
                        level=s.get("level", "普通"),
                        school_type=s.get("type_name", "综合"),
                        ranking=s.get("ranking"),
                        is_985=1 if "985" in str(s.get("level", "")) else 0,
                        is_211=1 if "211" in str(s.get("level", "")) else 0,
                        is_double_first_class=1 if "双一流" in str(s.get("level", "")) else 0,
                    )
                )
                total_api += 1
            db.commit()
            time.sleep(0.3)  # 礼貌间隔
        except Exception as e:
            print(f"    {province} 获取失败: {e}")

    # 尝试获取更多录取分数
    print("  尝试从 API 获取录取分数数据...")
    schools_in_db = db.query(School).filter(School.is_985 == 1).limit(20).all()
    for school in schools_in_db:
        try:
            scores = fetch_admission_scores(school.id)
            if not scores:
                continue
            for s in scores[:10]:
                exists = (
                    db.query(AdmissionScore)
                    .filter(
                        AdmissionScore.school_id == school.id,
                        AdmissionScore.province == s.get("province", ""),
                        AdmissionScore.year == s.get("year", 2024),
                        AdmissionScore.subject_type == s.get("subject_type", ""),
                    )
                    .first()
                )
                if exists:
                    continue
                db.add(
                    AdmissionScore(
                        school_id=school.id,
                        province=s.get("province", ""),
                        year=s.get("year", 2024),
                        batch=s.get("batch", "本科一批"),
                        subject_type=s.get("subject_type", "综合"),
                        min_score=s.get("min_score"),
                        avg_score=s.get("avg_score"),
                        max_score=s.get("max_score"),
                        min_rank=s.get("min_rank"),
                        plan_count=s.get("plan_count"),
                    )
                )
                total_api += 1
            db.commit()
            time.sleep(0.3)
        except Exception:
            continue

    print(f"  API 补充: {total_api} 条")
    return total_api


