"""Generate a local-only administrator environment file.

Example::

    python scripts/setup_admin_env.py
    set -a; . ./.env.admin.local; set +a
    uvicorn server.main:app --reload

The file is written with mode 0600 and contains a random password hash (the
plaintext is printed once, never stored). It is ignored by ``.gitignore`` via
the ``.env.*.local`` rule and must never be committed.
"""

from __future__ import annotations

import argparse
import json
import os
import secrets
import stat
import sys
from pathlib import Path

from server.admin.auth import hash_password


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate a local admin env file")
    parser.add_argument("--out", default=".env.admin.local")
    parser.add_argument("--username", default="operator")
    parser.add_argument("--role", default="operator", choices=["viewer", "operator", "admin"])
    parser.add_argument("--password", default="", help="optional; otherwise a random password is generated")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args(argv)

    out = Path(args.out)
    if out.exists() and not args.force:
        print(f"{out} already exists; use --force to overwrite", file=sys.stderr)
        return 2

    password = args.password or secrets.token_urlsafe(18)
    if len(password) < 12:
        print("password must be at least 12 characters", file=sys.stderr)
        return 2
    password_hash = hash_password(password)
    users = [{"username": args.username, "password_hash": password_hash, "role": args.role}]
    token_secret = secrets.token_hex(32)

    lines = [
        "# generated by scripts/setup_admin_env.py — local development only",
        f"ADMIN_USERS_JSON='{json.dumps(users, separators=(',', ':'))}'",
        f"ADMIN_TOKEN_SECRET={token_secret}",
        "QUALITY_TASK_MODE=auto",
        "APP_ENV=development",
    ]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(out, stat.S_IRUSR | stat.S_IWUSR)
    print(f"wrote {out} (mode 0600)")
    print(f"username: {args.username}")
    print(f"password: {password}")
    print(f"load it with: set -a; . ./{out}; set +a")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
