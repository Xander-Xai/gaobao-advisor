def main():
    print("=" * 60)
    print("  专业分类体系导入")
    print("=" * 60)

    init_db()
    db = get_session()

    try:
        new_count = 0
        update_count = 0
        skip_count = 0

        for name, category, sub_category, code, emp_rate, salary, hot, desc in MAJORS:
            existing = db.query(Major).filter(Major.name == name).first()
            if existing:
                # 更新就业数据
                if emp_rate:
                    existing.employment_rate = emp_rate
                if salary:
                    existing.avg_salary = salary
                existing.sub_category = sub_category
                existing.is_hot = hot
                if desc:
                    existing.description = desc
                update_count += 1
            else:
                major = Major(
                    name=name,
                    category=category,
                    sub_category=sub_category,
                    employment_rate=emp_rate,
                    avg_salary=salary,
                    median_salary=salary * 0.85 if salary else None,
                    is_hot=hot,
                    description=desc,
                    job_directions=json.dumps([]),  # 占位
                )
                db.add(major)
                new_count += 1

        db.commit()

        total = db.query(Major).count()
        hot_count = db.query(Major).filter(Major.is_hot == 1).count()

        print(f"\n[完成] 新增 {new_count} / 更新 {update_count} / 数据库共 {total} 个专业")
        print(f"  热门专业: {hot_count} 个")
        print("  覆盖学科门类: 12 个（哲学/经济学/法学/教育学/文学/历史学/理学/工学/农学/医学/军事学/管理学）")

    finally:
        db.close()


if __name__ == "__main__":
    main()
