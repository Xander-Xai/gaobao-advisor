def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    init_db()
    db = get_session()

    try:
        updated = 0
        not_found = 0
        already = 0

        for name, rank in RANKINGS_2024:
            school = db.query(School).filter(School.name == name).first()
            if not school:
                not_found += 1
                if not_found <= 10:
                    print(f"  [未找到] {name}")
                continue

            if school.ranking == rank:
                already += 1
                continue

            if not args.dry_run:
                school.ranking = rank

            updated += 1

        if not args.dry_run:
            db.commit()

        total = db.query(School).count()
        with_ranking = db.query(School).filter(School.ranking.isnot(None)).count()
        top_with_ranking = (
            db.query(School).filter((School.is_985 == 1) | (School.is_211 == 1), School.ranking.isnot(None)).count()
        )
        top_total = db.query(School).filter((School.is_985 == 1) | (School.is_211 == 1)).count()

        print(f"\n更新: {updated} | 已有: {already} | 未找到: {not_found}")
        print(f"排名覆盖率: {with_ranking}/{total} ({with_ranking / total * 100:.1f}%)")
        print(f"985/211覆盖率: {top_with_ranking}/{top_total} ({top_with_ranking / top_total * 100:.0f}%)")

    finally:
        db.close()


if __name__ == "__main__":
    main()
